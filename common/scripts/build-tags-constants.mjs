function parseCsvLine(line) {
  const out = []
  let cur = ''
  let i = 0
  while (i < line.length) {
    const c = line[i]
    if (c === '"') {
      i++
      while (i < line.length) {
        if (line[i] === '"') {
          if (line[i + 1] === '"') {
            cur += '"'
            i += 2
          } else {
            i++
            break
          }
        } else {
          cur += line[i]
          i++
        }
      }
    } else if (c === ',') {
      out.push(cur)
      cur = ''
      i++
    } else {
      cur += c
      i++
    }
  }
  out.push(cur)
  return out
}

const lines = RAW.trim()
  .split(/\r?\n/)
  .map((l) => l.trim())
  .filter(Boolean)
const header = parseCsvLine(lines[0])
const columns = header.map((genre, col) => {
  const tags = new Set()
  for (let r = 1; r < lines.length; r++) {
    const cells = parseCsvLine(lines[r])
    const cell = (cells[col] ?? '').trim()
    if (cell && cell !== ',' && cell !== '、') tags.add(cell.replace(/\r?\n/g, '').trim())
  }
  const tagList = [...tags]
  if (genre === 'コミュニティ／イベント') {
    const ordered = COMMUNITY_TAG_ORDER.filter((t) => tags.has(t))
    const rest = tagList.filter((t) => !COMMUNITY_TAG_ORDER.includes(t))
    if (rest.length > 0) {
      throw new Error(`コミュニティ／イベントに未定義のタグがあります: ${rest.join(', ')}`)
    }
    if (ordered.length !== tagList.length) {
      throw new Error('COMMUNITY_TAG_ORDER と CSV のタグ集合が一致しません')
    }
    return { genre, tags: ordered }
  }
  if (genre === '食／グルメ') {
    const ordered = FOOD_TAG_ORDER.filter((t) => tags.has(t))
    const rest = tagList.filter((t) => !FOOD_TAG_ORDER.includes(t))
    if (rest.length > 0) {
      throw new Error(`食／グルメに未定義のタグがあります: ${rest.join(', ')}`)
    }
    if (ordered.length !== tagList.length) {
      throw new Error('FOOD_TAG_ORDER と CSV のタグ集合が一致しません')
    }
    return { genre, tags: ordered }
  }
  if (genre === 'ベンチャー／スタートアップ') {
    const ordered = VENTURE_TAG_ORDER.filter((t) => tags.has(t))
    const rest = tagList.filter((t) => !VENTURE_TAG_ORDER.includes(t))
    if (rest.length > 0) {
      throw new Error(`ベンチャー／スタートアップに未定義のタグがあります: ${rest.join(', ')}`)
    }
    if (ordered.length !== tagList.length) {
      throw new Error('VENTURE_TAG_ORDER と CSV のタグ集合が一致しません')
    }
    return { genre, tags: ordered }
  }
  return { genre, tags: tagList.sort((a, b) => a.localeCompare(b, 'ja')) }
})

const outPath = join(__dirname, '../src/constants/tags.ts')
