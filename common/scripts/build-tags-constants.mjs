function parseCsvLine(line) {
  const out = []
  let cur = ''
  let i = 0
  while (i < line.length) {
    const c = line[i]
    if (c === '"') {
      i++
      while (i < line.length) {
        if (line[i] === '"') {
          if (line[i + 1] === '"') {
            cur += '"'
            i += 2
          } else {
            i++
            break
          }
        } else {
          cur += line[i]
          i++
        }
      }
    } else if (c === ',') {
      out.push(cur)
      cur = ''
      i++
    } else {
      cur += c
      i++
    }
  }
  out.push(cur)
  return out
}

const lines = RAW.trim()
  .split(/\r?\n/)
  .map((l) => l.trim())
  .filter(Boolean)
const header = parseCsvLine(lines[0])
const columns = header.map((genre, col) => {
  const tags = new Set()
  for (let r = 1; r < lines.length; r++) {
    const cells = parseCsvLine(lines[r])
    const cell = (cells[col] ?? '').trim()
    if (cell && cell !== ',' && cell !== '、') tags.add(cell.replace(/\r?\n/g, '').trim())
  }
  return { genre, tags: [...tags].sort((a, b) => a.localeCompare(b, 'ja')) }
})

